export function specializationStoryForState(state) {
  if (!specializationForState(state)) return null;
  if (state.age === 27) return specializationEvent(state,'craft');
  if (state.age === 38) return specializationEvent(state,'expert');
  if (state.age === 49) return specializationEvent(state,'legacy');
  return null;
}

export function applySpecializationIncome(state, baseAnnual) {
  const item = specializationForState(state);
  if (!item) return Math.max(0,Math.round(baseAnnual));
  return Math.max(0,Math.round(baseAnnual * item.incomeMultiplier + item.monthlyBonus * 12));
}

export function allSpecializationRanks() {
  const result={};
  for (const [profession,group] of Object.entries(SPECIALIZATIONS)) {
    for (const [key,item] of Object.entries(group)) result[`${profession}:${key}`]=item.ranks;
  }
  return result;
}
