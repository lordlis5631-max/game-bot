const stripAction = (text='') => text
  .replace(/[\u{1F000}-\u{1FAFF}\u2600-\u27BF]/gu,'')
  .replace(/·\s*🎲\s*\d+%/g,'')
  .replace(/·\s*⏱\s*\d+/g,'')
  .trim();

