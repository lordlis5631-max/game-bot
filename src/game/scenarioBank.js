function matchesStory(event, state) {
  if (state.age < event.minAge || state.age > event.maxAge) return false;
  const flags = state.flags || [];
  const seen = state.seenEvents || [];
  if (seen.includes(event.id)) return false;
  if (event.requiresAny && !event.requiresAny.some((flag) => flags.includes(flag))) return false;
  if (event.requiresAll && !event.requiresAll.every((flag) => flags.includes(flag))) return false;
  return true;
}

function hashNumber(seed, age, salt = 0) {
  let x = (Number(seed || 1) * 1103515245 + age * 12345 + salt * 2654435761) >>> 0;
  x ^= x >>> 16;
  x = Math.imul(x, 2246822519) >>> 0;
  x ^= x >>> 13;
  return x >>> 0;
}

export function storylineForState(state) {
  const eligible = STORY_EVENTS.filter((event) => matchesStory(event, state));
  if (!eligible.length) return null;
  // Story events are intentionally occasional so a run still explores the wider 432-event bank.
  const roll = hashNumber(state.seed, state.age, (state.seenEvents || []).length) % 100;
  if (roll >= 42) return null;
  return eligible[hashNumber(state.seed, state.age, 91) % eligible.length];
}

export function scenarioForState(state) {
  const seen = new Set(state.seenEvents || []);
  let eligible = SCENARIO_BANK.filter((event) => state.age >= event.minAge && state.age <= event.maxAge && !seen.has(event.id));
  if (!eligible.length) eligible = SCENARIO_BANK.filter((event) => state.age >= event.minAge && state.age <= event.maxAge);
  if (!eligible.length) throw new Error(`No scenario configured for age ${state.age}`);
  return eligible[hashNumber(state.seed, state.age, seen.size) % eligible.length];
}

