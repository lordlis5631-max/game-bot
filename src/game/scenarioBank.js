function scaleEffects(effects, stage) {
  const scaled = { ...effects };
  if (typeof scaled.money === 'number') scaled.money = Math.round(scaled.money * stage.money);
  if (typeof scaled.debt === 'number') scaled.debt = Math.round(scaled.debt * stage.money);
  return scaled;
}

